function Sidebar({ activeItem, onSelectItem, isOpen, onClose, counts = {} }) {
  return (
    <>
      {/* Mobile backdrop */}
      {isOpen && (
        <div
          className="sidebar-backdrop"
          onClick={onClose}
          aria-hidden="true"
        />
      )}

      <aside className={`sidebar ${isOpen ? "sidebar-open" : ""}`} aria-label="Sidebar Navigation">
        {/* Simple Clean Header */}
        <div className="sidebar-header">
          <div className="sidebar-title-wrapper">
            <span className="sidebar-brand-badge">S</span>
            <span className="sidebar-brand-name">Scalefox</span>
          </div>
          <button
            type="button"
            className="sidebar-close-btn"
            onClick={onClose}
            aria-label="Close menu"
          >
            ✕
          </button>
        </div>

        {/* Clean Menu Navigation */}
        <nav className="sidebar-nav">
          {SIDEBAR_SECTIONS.map((section) => (
            <div key={section.id} className="sidebar-section">
              <div className="sidebar-section-title">{section.title}</div>
              <ul className="sidebar-menu-list">
                {section.items.map((item) => {
                  const isActive = activeItem === item.id;
                  let displayBadge = item.badge;
                  if (item.id === "All Products" && counts.all !== undefined) {
                    displayBadge = String(counts.all);
                  } else if (item.id === "Flipkart" && counts.flipkart !== undefined) {
                    displayBadge = String(counts.flipkart);
                  } else if (item.id === "Amazon" && counts.amazon !== undefined) {
                    displayBadge = String(counts.amazon);
                  }

                  return (
                    <li key={item.id} className="sidebar-menu-item">
                      <button
                        type="button"
                        className={`sidebar-link ${isActive ? "active" : ""}`}
                        onClick={() => {
                          onSelectItem(item.id);
                          if (onClose) onClose();
                        }}
                      >
                        <span className="sidebar-icon">{item.icon}</span>
                        <span className="sidebar-label">{item.label}</span>
                        {displayBadge && (
                          <span className="sidebar-item-badge">{displayBadge}</span>
                        )}
                      </button>
                    </li>
                  );
                })}
              </ul>
            </div>
          ))}
        </nav>
      </aside>
    </>
  );
}

export default Sidebar;
